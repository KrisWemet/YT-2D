#!/usr/bin/env python3
"""Measure the tickle Short sprites, copy them to public/tickle/, write src/tickle/sprites.ts"""
import json, shutil, os, sys
import numpy as np, cv2
from PIL import Image
sys.path.insert(0, '../hurricane')
PUB = '../../public/tickle'

def load(n):
    im = np.asarray(Image.open(f'keyed/{n}.png')).astype(np.int32)
    return im[..., :3], im[..., 3]

def head_feet(n):
    rgb, a = load(n); h, w = a.shape
    a8 = (a > 128).astype(np.uint8); ff = a8.copy()
    cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    solid = np.where(ff == 2, 0, 1).astype(np.uint8)
    dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
    dt2 = dt.copy(); dt2[int(0.4 * h):] = 0  # head = largest inscribed disc in the upper part
    hy, hx = np.unravel_index(dt2.argmax(), dt2.shape)
    ys = np.nonzero(a8.any(1))[0]; yb = ys.max()
    band = a8[int(yb - 0.035 * h):yb + 1]; xs = np.nonzero(band.any(0))[0]
    return dict(w=w, h=h, head=[float(hx), float(hy), float(dt2[hy, hx])], feet=[float((xs.min() + xs.max()) / 2), float(yb)])

out = {}
for n in ['g_self', 'g_laugh', 'g_palm']:
    out[n] = head_feet(n); out[n]['file'] = f'tickle/{n}.png'
# open palm of g_palm: rightmost opaque pixel in the chest band, palm centre a bit inside it
rgb, a = load('g_palm'); h, w = a.shape
band = a[int(0.3 * h):int(0.6 * h)] > 128
ys, xs = np.nonzero(band); i = xs.argmax()
out['g_palm']['palm'] = [float(xs[i] - 70), float(ys[i] + int(0.3 * h) + 10)]
# robot: feather tip = leftmost opaque pixel; eyes = cyan blobs; base bottom
rgb, a = load('robot'); h, w = a.shape
ys, xs = np.nonzero(a > 128); i = xs.argmin()
hsv = cv2.cvtColor(rgb.astype(np.uint8), cv2.COLOR_RGB2HSV).astype(np.int32)
cyan = ((hsv[..., 0] > 80) & (hsv[..., 0] < 100) & (hsv[..., 1] > 120) & (hsv[..., 2] > 150) & (a > 200)).astype(np.uint8)
n_, lab, st, cen = cv2.connectedComponentsWithStats(cyan, 8)
eyes = sorted([[float(c[0]), float(c[1]), float(np.sqrt(s[4] / np.pi))] for c, s in zip(cen[1:], st[1:]) if s[4] > 200])
out['robot'] = dict(file='tickle/robot.png', w=w, h=h, tip=[float(xs[i]), float(ys[i])], base=[float((xs[ys > ys.max() - 20].min() + xs[ys > ys.max() - 20].max()) / 2), float(ys.max())], eyes=eyes)
for n in ['brain', 'feather']:
    rgb, a = load(n); h, w = a.shape
    out[n] = dict(file=f'tickle/{n}.png', w=w, h=h)
# feather quill end = lowest opaque pixel
rgb, a = load('feather'); ys, xs = np.nonzero(a > 128); i = ys.argmax(); out['feather']['quill'] = [float(xs[i]), float(ys[i])]
os.makedirs(PUB, exist_ok=True)
for n in out: shutil.copy(f'keyed/{n}.png', f'{PUB}/{n}.png')
json.dump(out, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/tickle', exist_ok=True)
open('../../src/tickle/sprites.ts', 'w').write('// generated by images/tickle/prep.py\nexport const K = ' + json.dumps(out, indent=1, default=lambda v: round(float(v), 2)) + ' as const;\n')
for k, v in out.items(): print(k, {kk: vv for kk, vv in v.items() if kk != 'file'})
