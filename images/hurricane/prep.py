#!/usr/bin/env python3
"""Measure the hurricane Short sprites, copy them to public/hurricane/, write src/hurricane/sprites.ts"""
import json, shutil, os
import numpy as np, cv2
from PIL import Image

PUB = '../../public/hurricane'
def load(n):
    im = np.asarray(Image.open(f'keyed/{n}.png')).astype(np.int32)
    return im[..., :3], im[..., 3]
def head_feet(n):
    rgb, a = load(n); h, w = a.shape
    a8 = (a > 128).astype(np.uint8); ff = a8.copy()
    cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    solid = np.where(ff == 2, 0, 1).astype(np.uint8)
    dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
    # head = largest inscribed disc in the upper 45% (the bomb can be bigger than the head elsewhere)
    dt2 = dt.copy(); dt2[int(0.45 * h):] = 0
    hy, hx = np.unravel_index(dt2.argmax(), dt2.shape)
    ys = np.nonzero(a8.any(1))[0]; yb = ys.max()
    band = a8[int(yb - 0.035 * h):yb + 1]; xs = np.nonzero(band.any(0))[0]
    return dict(w=w, h=h, head=[float(hx), float(hy), float(dt2[hy, hx])], feet=[float((xs.min() + xs.max()) / 2), float(yb)])
def bomb_in(n):
    rgb, a = load(n)
    hsv = cv2.cvtColor(rgb.astype(np.uint8), cv2.COLOR_RGB2HSV).astype(np.int32)
    yellow = (hsv[..., 0] >= 18) & (hsv[..., 0] <= 38) & (hsv[..., 1] > 120) & (hsv[..., 2] > 150) & (a > 200)
    n_, lab, st, cen = cv2.connectedComponentsWithStats(yellow.astype(np.uint8), 8)
    k = 1 + np.argmax(st[1:, 4]); ycx, ycy = cen[k]
    dark = (rgb.sum(2) < 180) & (a > 200)
    body = (dark | yellow).astype(np.uint8)
    body = cv2.morphologyEx(body, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
    # inscribed disc near the yellow symbol = bomb body
    dt = cv2.distanceTransform(body, cv2.DIST_L2, 5)
    win = np.zeros_like(dt); r0 = int(np.sqrt(st[k, 4] / np.pi) * 2.2)
    y0, x0 = int(ycy), int(ycx)
    win[max(0, y0 - r0):y0 + r0, max(0, x0 - r0):x0 + r0] = 1
    dt *= win
    by, bx = np.unravel_index(dt.argmax(), dt.shape)
    return dict(cx=float(bx), cy=float(by), r=float(dt[by, bx]), sym=[float(ycx), float(ycy)])
out = {}
for n in ['g_bomb_hold', 'g_windup', 'g_throw', 'g_scared']:
    out[n] = head_feet(n); out[n]['file'] = f'hurricane/{n}.png'; shutil.copy(f'keyed/{n}.png', f'{PUB}/{n}.png')
out['g_windup']['bomb'] = bomb_in('g_windup')
out['g_bomb_hold']['bomb'] = bomb_in('g_bomb_hold')
rgb, a = load('bomb'); h, w = a.shape
out['bomb'] = dict(file='hurricane/bomb.png', w=w, h=h, body=bomb_in('bomb'))
# fuse tip of the bomb sprite: topmost opaque pixel
ys, xs = np.nonzero(a > 200); i = ys.argmin(); out['bomb']['fuse'] = [float(xs[i]), float(ys[i])]
shutil.copy('keyed/bomb.png', f'{PUB}/bomb.png')
rgb, a = load('hurricane'); h, w = a.shape
dark = (rgb.sum(2) < 330) & (rgb.sum(2) > 150) & (a > 200)  # mid-grey eye fill
n_, lab, st, cen = cv2.connectedComponentsWithStats(dark.astype(np.uint8), 8)
k = 1 + np.argmax(st[1:, 4]); ex, ey = cen[k]
ys, xs = np.nonzero(a > 128); R = float(np.hypot(xs - ex, ys - ey).max())
out['hurricane'] = dict(file='hurricane/hurricane.png', w=w, h=h, eye=[float(ex), float(ey)], eyeR=float(np.sqrt(st[k, 4] / np.pi)), R=R)
shutil.copy('keyed/hurricane.png', f'{PUB}/hurricane.png')
rgb, a = load('houses'); h, w = a.shape
base = int(np.nonzero((a > 128).sum(1) > 0.3 * w)[0].max())
out['houses'] = dict(file='hurricane/houses.png', w=w, h=h, base=base)
shutil.copy('keyed/houses.png', f'{PUB}/houses.png')
json.dump(out, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/hurricane', exist_ok=True)
open('../../src/hurricane/sprites.ts', 'w').write('// generated by images/hurricane/prep.py\nexport const H = ' + json.dumps(out, indent=1, default=lambda v: round(float(v), 2)) + ' as const;\n')
for k, v in out.items(): print(k, {kk: (vv if not isinstance(vv, float) else round(vv, 1)) for kk, vv in v.items() if kk != 'file'})
