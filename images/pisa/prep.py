#!/usr/bin/env python3
"""Measure the Pisa Short sprites, copy them to public/pisa/, write src/pisa/sprites.ts"""
import json, shutil, os
import numpy as np, cv2
from PIL import Image
PUB = '../../public/pisa'

def load(n):
    im = np.asarray(Image.open(f'keyed/{n}.png')).astype(np.int32)
    return im[..., :3], im[..., 3]

out = {}
# scientist pushing: head (largest disc in the upper 40%), feet, palms (leftmost opaque pixel above the head bottom)
rgb, a = load('g_push'); h, w = a.shape
a8 = (a > 128).astype(np.uint8); ff = a8.copy()
cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
solid = np.where(ff == 2, 0, 1).astype(np.uint8)
dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5); dt[int(0.4 * h):] = 0
hy, hx = np.unravel_index(dt.argmax(), dt.shape)
ys, xs = np.nonzero(a8); yb = ys.max()
band = a8[int(yb - 0.035 * h):yb + 1]; bx = np.nonzero(band.any(0))[0]
top = a8[:int(0.45 * h)]; ty, tx = np.nonzero(top); i = tx.argmin()
out['g_push'] = dict(file='pisa/g_push.png', w=w, h=h, head=[float(hx), float(hy), float(dt[hy, hx])],
                     feet=[float((bx.min() + bx.max()) / 2), float(yb)], palm=[float(tx[i]), float(ty[i])],
                     backFoot=[float(bx.max()), float(yb)])
# tower: base centre, top centre, axis angle, base width, height
rgb, a = load('tower'); h, w = a.shape
m = a > 128
rows = np.nonzero(m.any(1))[0]; y0, y1 = rows.min(), rows.max()
def mid(y):
    xs = np.nonzero(m[y])[0]; return (xs.min() + xs.max()) / 2, xs.max() - xs.min()
cb, wb = mid(y1 - 6); ct, wt = mid(y0 + 30)
# axis from a robust fit of row midpoints across the shaft
ysamp = np.arange(int(y0 + 0.2 * (y1 - y0)), int(y1 - 0.1 * (y1 - y0)), 8)
mids = np.array([mid(y)[0] for y in ysamp])
k, c = np.polyfit(ysamp, mids, 1)
ang = float(np.degrees(np.arctan(k)))  # + means the top is further LEFT (x shrinks going up)
out['tower'] = dict(file='pisa/tower.png', w=w, h=h, base=[float(k * y1 + c), float(y1)], top=[float(k * y0 + c), float(y0)],
                    baseW=float(wb), axisDeg=ang, shaftW=float(np.median([mid(y)[1] for y in ysamp])))
os.makedirs(PUB, exist_ok=True)
for n in out: shutil.copy(f'keyed/{n}.png', f'{PUB}/{n}.png')
json.dump(out, open('sprites.json', 'w'), indent=1)
os.makedirs('../../src/pisa', exist_ok=True)
open('../../src/pisa/sprites.ts', 'w').write('// generated by images/pisa/prep.py\nexport const P = ' + json.dumps(out, indent=1, default=lambda v: round(float(v), 2)) + ' as const;\n')
for kk, v in out.items(): print(kk, {a_: b_ for a_, b_ in v.items() if a_ != 'file'})
